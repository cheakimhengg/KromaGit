const out = {}
for (const [name, icon] of Object.entries(MAP)) {
  const key = set.icons[icon] ? icon : set.aliases?.[icon]?.parent
  const data = key && set.icons[key]
  if (!data) throw new Error(`Hugeicons icon not found: ${icon}`)
  out[name] = { body: data.body, w: data.width ?? set.width ?? 24, h: data.height ?? set.height ?? 24 }
}

const file = `// Generated by scripts/gen-icons.mjs from Hugeicons free (MIT). Do not edit.
export const ICONS: Record<string, { body: string; w: number; h: number }> = ${JSON.stringify(out, null, 1)}
`
fs.writeFileSync(path.join(root, 'src/lib/icons.generated.ts'), file)
